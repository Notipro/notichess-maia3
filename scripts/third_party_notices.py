"""Writes THIRD-PARTY-NOTICES on stdout: every crate built into the release
executables (normal and build dependencies for the four release targets,
from Cargo.lock), its license, and the license files its package ships, then
the musl C library of the Linux executable.

    python3 scripts/third_party_notices.py > THIRD-PARTY-NOTICES

Standard library only. Needs the crate sources (`cargo fetch` is enough). The
output depends only on Cargo.lock and licenses/, so the CI checks the
committed file is up to date.

A crate whose package ships no license file takes the files of
licenses/<crate>/ (copied from its repository at the released commit), or else
those of another shipped crate from the same repository.
"""

import json
import subprocess
import sys
from pathlib import Path

TARGETS = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "x86_64-pc-windows-msvc",
    "x86_64-unknown-linux-musl",
]
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE")

HEADER = """THIRD-PARTY NOTICES for notichess-maia3

notichess-maia3: Copyright (C) 2026 NotiChess contributors, licensed under
the GNU Affero General Public License version 3 (LICENSE).

The model it runs, maia3-5m.onnx (published separately), is converted from the
Maia3-5M weights of the CSSLab, University of Toronto
(https://huggingface.co/UofTCSSLab/Maia3-5M), licensed under the AGPL-3.0. The
input and output encoding follows the official code,
https://github.com/CSSLab/maia3 (AGPL-3.0).

The executables contain the Rust crates below: normal and build dependencies
for {targets}, as locked in Cargo.lock. Generated by
scripts/third_party_notices.py.

The Linux executable also contains the musl C library, listed after the
crates.
"""

# Not a crate: the C library that the Rust toolchain links statically into the
# x86_64-unknown-linux-musl executable (README, "Linux"). licenses/musl/COPYRIGHT
# is the COPYRIGHT file of musl at its tag v1.2.5.
MUSL = (
    "musl 1.2.5: MIT; https://musl.libc.org, linked statically into the Linux "
    "executable, as shipped by the Rust toolchain for x86_64-unknown-linux-musl"
)


def metadata():
    cmd = ["cargo", "metadata", "--locked", "--format-version", "1"]
    for target in TARGETS:
        cmd += ["--filter-platform", target]
    return json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


def shipped_packages(meta):
    """Packages reachable from the root without dev-dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, todo = set(), [root]
    while todo:
        for dep in nodes[todo.pop()]["deps"]:
            if any(k["kind"] != "dev" for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    packages = [p for p in meta["packages"] if p["id"] in seen]
    return sorted(packages, key=lambda p: (p["name"], p["version"]))


VENDORED = Path(__file__).resolve().parent.parent / "licenses"


def license_files(package):
    folder = Path(package["manifest_path"]).parent
    vendored = VENDORED / package["name"]
    if vendored.is_dir():
        return sorted(f for f in vendored.iterdir() if f.is_file())
    files = [f for f in folder.iterdir() if f.is_file() and f.name.upper().startswith(LICENSE_PREFIXES)]
    if package.get("license_file"):
        extra = folder / package["license_file"]
        if extra.is_file() and extra not in files:
            files.append(extra)
    return sorted(files, key=lambda f: f.name)


def text_of(path):
    text = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
    return "\n".join(line.rstrip() for line in text.strip("\n").split("\n"))


def main():
    packages = shipped_packages(metadata())
    out = [HEADER.format(targets=", ".join(TARGETS)), "", "CRATES", ""]
    files = {p["id"]: license_files(p) for p in packages}
    by_repository = {}
    for p in packages:
        if files[p["id"]] and p.get("repository"):
            by_repository.setdefault(p["repository"].rstrip("/"), p)

    texts = {}  # text -> ["crate version (file)"]
    for p in packages:
        crate = f"{p['name']} {p['version']}"
        out.append(f"{crate}: {p.get('license') or 'no license field'}; {p.get('repository') or 'no repository'}")
        own, origin = files[p["id"]], ""
        if not own:
            donor = by_repository.get((p.get("repository") or "").rstrip("/"))
            if donor is None:
                sys.exit(f"{crate} ships no license file: add licenses/{p['name']}/")
            own, origin = files[donor["id"]], f", as shipped by {donor['name']} {donor['version']}"
        for f in own:
            texts.setdefault(text_of(f), []).append(f"{crate} ({f.name}{origin})")

    out += ["", "C LIBRARY", "", MUSL]
    texts.setdefault(text_of(VENDORED / "musl" / "COPYRIGHT"), []).append("musl 1.2.5 (COPYRIGHT)")

    out += ["", "LICENSE TEXTS", ""]
    for text, users in sorted(texts.items(), key=lambda kv: kv[1][0]):
        out.append("=" * 78)
        out.append("Used by: " + ", ".join(users))
        out.append("=" * 78)
        out.append("")
        out.append(text)
        out.append("")
    sys.stdout.write("\n".join(out).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
